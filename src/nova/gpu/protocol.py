"""供管理器消费的窄接口；vLLM 适配在后续阶段实现，不暴露管理服务。"""

from typing import Protocol


class ModelBackend(Protocol):
    model: str

    async def unload_model(self, name: str) -> dict: ...
    async def sleep_model(self, name: str) -> dict: ...
    async def wake_model(self, *, runtime: dict | None = None) -> dict: ...
    async def get_model_status(self) -> list[dict]: ...
    async def get_gpu_memory_usage(self) -> dict: ...
    async def generate(self, prompt: str, *, runtime: dict | None = None) -> dict: ...
    async def list_installed_models(self) -> list[str]: ...
    async def ensure_local_model(self, model: str) -> None: ...
    async def stream_chat(
        self, model: str, messages: list[dict], on_delta, *, runtime: dict | None = None,
        control=None,
    ) -> dict: ...
